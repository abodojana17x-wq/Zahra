    /**
     * البحث في الدروس
     */
    fun searchLessons(query: String, topK: Int = 5): List<IslamicLesson> {
        val normalized = query.lowercase().trim()
        val keywords = normalized.split("\\s+".toRegex())
        
        val scored = lessons.map { lesson ->
            var score = 0
            for (keyword in keywords) {
                if (lesson.title.contains(keyword, ignoreCase = true)) score += 3
                if (lesson.content.contains(keyword, ignoreCase = true)) score += 2
                if (lesson.keywords.any { it.contains(keyword, ignoreCase = true) }) score += 1
                if (lesson.category.labelAr.contains(keyword, ignoreCase = true)) score += 1
            }
            Pair(lesson, score)
        }.filter { it.second > 0 }
        
        return scored.sortedByDescending { it.second }
            .take(topK)
            .map { it.first }
    }
    

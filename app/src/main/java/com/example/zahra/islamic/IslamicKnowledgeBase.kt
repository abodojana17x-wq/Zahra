    /**
     * تنسيق الدرس للعرض
     */
    fun formatLesson(lesson: IslamicLesson): String {
        val sb = StringBuilder()
        sb.append("${lesson.category.emoji} **${lesson.title}**\n\n")
        sb.append(lesson.content)
        sb.append("\n\n")
        if (lesson.quranRef != null) {
            sb.append("📖 ${lesson.quranRef}\n")
        }
        if (lesson.hadithRef != null) {
            sb.append("📜 ${lesson.hadithRef}\n")
        }
        sb.append("\nالمصدر: ${lesson.source}")
        return sb.toString()
    }
    

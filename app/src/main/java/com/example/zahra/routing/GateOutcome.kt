package com.example.zahra.routing

/**
 * مخرج بوابة الثقة ([ConfidenceGate]) — ثلاث قيم فقط، وفق [plans/01-honesty-routing.md] (المسار D).
 *
 * - [ANSWER]: تحقق سياسة البوابة ولدى الطلب مصدر أو أداة مناسبة.
 * - [CLARIFY]: السؤال غير واضح؛ نُبدّل المستخدم بخيارات مأخوذة من أعلى النيات الفعلية، لا كلمات عشوائية.
 * - [ABSTAIN]: امتناع صريح؛ لا قالب معلوماتي مفبرك ولا إعادة تدوير سؤال المستخدم.
 */
enum class GateOutcome {
  /** الإجابة مدعومة بمصدر أو أداة. */
  ANSWER,
  /**طلب توضيح مع 2–3 خيارات من النيات الفعلية الأعلى درجة. */
  CLARIFY,
  /** الامتناع الصادق عن الإجابة. */
  ABSTAIN
}

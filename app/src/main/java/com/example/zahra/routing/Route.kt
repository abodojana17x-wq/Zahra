package com.example.zahra.routing

/**
 * مسار القرار في زهرة — يحدّد أين يُنفّذ الطلب، لا ماذا يُقال للمستخدم.
 *
 * القيم مرتبة حسب أولوية التوجيه الموثقة في [plans/01-honesty-routing.md]:
 * الأمان/رفض → أوامر النظام → الأدوات الحتمية → حقائق بمصدر → برمجة → دين → مشاعر/حوار → امتناع.
 */
enum class Route {
  /** أوامر نظامية (مهام، ملاحظات، جدولة، تصحيح حقائق، تراجع، شخصية). */
  SYSTEM,
  /** أدوات حتمية محلية (حساب، تحويل وحدات، وقت/تاريخ). */
  CALC,
  /** تحويل وحدات قياسية. */
  UNIT,
  /** وقت وتاريخ. */
  TIME,
  /** حقائق من قاعدة المعرفة المعتمدة مع مصدر. */
  FACT,
  /** برمجة / توليد محلي (صور، بطاقات، بكسل). */
  CODE,
  /** حقائق دينية من المصادر المدمجة (قرآن، حديث، فقه، مواقيت). */
  RELIGION,
  /** حديث اجتماعي وتحيات ووداع وشكر ومساعدة. */
  SOCIAL,
  /** مشاعر ودعم حوار أساسي (بدون ادعاء تشخيص أو معالجة). */
  EMOTION,
  /** رفض صلب لطلب impermissible/غير آمن. */
  REFUSE,
  /** لا مسار ممكن → אמتناع. */
  UNKNOWN
}
